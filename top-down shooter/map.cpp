void drawwall(sf::RenderWindow &window) {
    sf::RectangleShape wall(sf::Vector2f(48, 48)); 
    wall.setFillColor(sf::Color::Black); 

    for (int i = 0; i < maph; i++) {
        for (int j = 0; j < mapw; j++) {
            if (tileMap[i][j] == 2) {
                playerX = j * 32 + 32;
                playerY = i * 32 + 32;
                tileMap[i][j] = 0;
            }
            if (tileMap[i][j] == 1) {
                wall.setPosition(j * 32, i * 32); 
                window.draw(wall);
            }

        }
    }
}